export function interpretTrait(axisIndex:number, type:"sin"|"virtue", score:number) {
  const data=(type==="sin"?shadow:light)[axisIndex];
  const band=score<35?0:score<70?1:2;
  return {name:type==="sin"?axes[axisIndex].sin:axes[axisIndex].virtue,score,band,theme:data.theme,body:data.patterns[band],prompt:data.tryThis,concept:data.concept};
}

export function reportReflection(report:Report):string {
  const strong=report.scores.filter(p=>p.sin>=70&&p.virtue>=70).length;
  const contrasting=report.scores.filter(p=>Math.abs(p.sin-p.virtue)>=35).length;
  if(strong) return `你有 ${strong} 组‘本能与美德都较常出现’的组合。这不是逻辑矛盾：不同情境可能激活不同回应。比起给自己定性，回想‘哪种场景下我会走向哪一边’更有帮助。`;
  if(contrasting) return `你有 ${contrasting} 组两项频率相差较明显的对照。这可能是最近生活情境与行为习惯留下的痕迹，不表示任何维度是天生固定的。`;
  return "你的多项维度没有形成尖锐的对立轮廓。这也许意味着反应会随情境变化；与其寻找唯一标签，不如记住让你有所触动的具体问题。";
}
